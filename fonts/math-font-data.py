# Writes math-font-data.typ: per-letter numbers from the math font that
# fixes.typ needs to place accents and scripts the way Typst's PDF does.
# Run from this folder after changing the font (needs fontTools):
#     python math-font-data.py > math-font-data.typ
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.boundsPen import BoundsPen

FONT = "NewCMMath-Book.woff"
f = TTFont(FONT)
cmap, glyphs, hmtx, math = f.getBestCmap(), f.getGlyphSet(), f["hmtx"], f["MATH"].table
em = f["head"].unitsPerEm
const = {k: getattr(math.MathConstants, k) for k in dir(math.MathConstants) if k[0].isupper()}
c = lambda k: const[k].Value if hasattr(const[k], "Value") else const[k]

info = math.MathGlyphInfo
accent_spot = dict(zip(info.MathTopAccentAttachment.TopAccentCoverage.glyphs,
                       [v.Value for v in info.MathTopAccentAttachment.TopAccentAttachment]))
italic = dict(zip(info.MathItalicsCorrectionInfo.Coverage.glyphs,
                  [v.Value for v in info.MathItalicsCorrectionInfo.ItalicsCorrection]))
kerns = info.MathKernInfo

def ink(g):
    pen = BoundsPen(glyphs); glyphs[g].draw(pen); return pen.bounds or (0, 0, 0, 0)

def kern_at(g, corner, height):
    # The OpenType MATH kern of glyph g at a corner, at a height above its baseline.
    if kerns is None or g not in kerns.MathKernCoverage.glyphs: return 0
    k = getattr(kerns.MathKernInfoRecords[kerns.MathKernCoverage.glyphs.index(g)], corner + "MathKern")
    if k is None: return 0
    for h, v in zip(k.CorrectionHeight, k.KernValue):
        if height < h.Value: return v.Value
    return k.KernValue[-1].Value

# The characters Typst writes in math, and the glyphs it draws for them:
# italic Latin and lowercase Greek, upright capital Greek and digits.
letters = [(ch, 0x210E if ch == "h" else 0x1D44E + i) for i, ch in enumerate("abcdefghijklmnopqrstuvwxyz")]
letters += [(ch, 0x1D434 + i) for i, ch in enumerate("ABCDEFGHIJKLMNOPQRSTUVWXYZ")]
letters += [(ch, 0x1D6FC + i) for i, ch in enumerate("αβγδεζηθικλμνξοπρςστυφχψω")]
letters += list(zip("ϵϑϰϕϱϖ", (0x1D716, 0x1D717, 0x1D718, 0x1D719, 0x1D71A, 0x1D71B)))
letters += [(ch, ord(ch)) for ch in "ΑΒΓΔΕΖΗΘΙΚΛΜΝΞΟΠΡΣΤΥΦΧΨΩ0123456789"]

# Typical scripts, at script size: an italic n below, a 2 above.
scale = c("ScriptPercentScaleDown") / 100
sub_ascent = ink(cmap[0x1D45B])[3] * scale
sup_descent = max(0, -ink(cmap[0x32])[1] * scale)

def script_shift(g):
    # How far Chrome's script placement (MathML Core) is from Typst's, for a
    # one-letter base: Typst ignores the letter's height and depth (as TeX
    # does), and adds its italic correction and math kern; Chrome does not.
    x0, y0, x1, y1 = ink(g)
    ascent, descent = y1, max(0, -y0)
    down = max(c("SubscriptShiftDown"), sub_ascent - c("SubscriptTopMax"))
    up = max(c("SuperscriptShiftUp"), c("SuperscriptBottomMin") + sup_descent)
    chrome_down = max(down, descent + c("SubscriptBaselineDropMin"))
    chrome_up = max(up, ascent - c("SuperscriptBaselineDropMax"))
    sub_kern = max(kern_at(g, "BottomRight", sub_ascent - down), kern_at(g, "BottomRight", down - descent))
    sup_kern = max(kern_at(g, "TopRight", ascent - up), kern_at(g, "TopRight", up - sup_descent))
    return (sub_kern / em, (chrome_down - down) / em, (italic.get(g, 0) + sup_kern) / em, (chrome_up - up) / em)

def table(name, rows, width=74):
    out, line = [], ""
    for item in rows:
        if len(line) + len(item) + 2 > width: out.append(line.rstrip()); line = ""
        line += item + ", "
    out.append(line.rstrip())
    return f"#let {name} = (\n  " + "\n  ".join(out) + "\n)"

fmt = lambda v: f"{v:.3f}".replace("-0.000", "0.000")
accents, scripts = [], []
for ch, cp in letters:
    g = cmap.get(cp)
    if g is None: continue
    if g in accent_spot and not "Α" <= ch <= "Ω" and not ch.isdigit():
        v = (accent_spot[g] - hmtx[g][0] / 2) / em
        if abs(v) >= 0.0005: accents.append(f'"{ch}": {fmt(v)}')
    s = script_shift(g)
    if any(abs(v) >= 0.0005 for v in s):
        scripts.append(f'"{ch}": (' + ", ".join(fmt(v) for v in s) + ")")

sys.stdout.reconfigure(encoding="utf-8")
print(f"// Generated by math-font-data.py from {FONT}; do not edit by hand.")
print("// All lengths in em of the math font.")
print()
print("// Each italic letter's accent spot right of its center (MATH TopAccentAttachment).")
print(table("accent-shift", accents))
print()
print("// For a letter with a subscript or superscript: how far to move the")
print("// subscript right, the subscript up, the superscript right, and the")
print("// superscript down, to go from Chrome's placement to Typst's.")
print(table("script-shift", scripts, width=78))
